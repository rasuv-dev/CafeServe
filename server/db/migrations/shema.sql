-- =====================================================
-- 1. ROLES TABLE
-- =====================================================

CREATE TABLE roles (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255),
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- 2. STAFF TABLE
-- =====================================================

CREATE TABLE staff (
    staff_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    role_id BIGINT NOT NULL,

    full_name VARCHAR(100) NOT NULL,
    username VARCHAR(50) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    profile_image VARCHAR(255),

    status VARCHAR(20) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Inactive')),

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_staff_role
        FOREIGN KEY (role_id)
        REFERENCES roles(role_id)
        ON DELETE RESTRICT
);


-- =====================================================
-- 3. CATEGORIES TABLE
-- =====================================================

CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    category_name VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255),

    status VARCHAR(20) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Inactive')),

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- 4. MENU ITEMS TABLE
-- =====================================================

CREATE TABLE menu_items (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    category_id BIGINT NOT NULL,

    item_name VARCHAR(150) NOT NULL,
    description TEXT,

    price NUMERIC(10,2) NOT NULL
        CHECK (price >= 0),

    image VARCHAR(255),

    is_available BOOLEAN NOT NULL DEFAULT TRUE,

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_menu_category
        FOREIGN KEY (category_id)
        REFERENCES categories(category_id)
        ON DELETE RESTRICT
);


-- =====================================================
-- 5. CUSTOMERS TABLE
-- =====================================================

CREATE TABLE customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    customer_name VARCHAR(100) NOT NULL,

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
);


-- =====================================================
-- 6. ORDERS TABLE
-- =====================================================

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_number VARCHAR(30) NOT NULL UNIQUE,

    customer_id BIGINT,

    -- Customer name snapshot
    customer_name VARCHAR(100),

    order_date DATE NOT NULL DEFAULT CURRENT_DATE,
    order_time TIME NOT NULL DEFAULT LOCALTIME,

    notes TEXT,

    total_amount NUMERIC(10,2) NOT NULL DEFAULT 0
        CHECK (total_amount >= 0),

    payment_method VARCHAR(30) NOT NULL
        CHECK (payment_method IN ('Cash', 'Online', 'Other')),

    payment_status VARCHAR(20) NOT NULL DEFAULT 'Not Paid'
        CHECK (payment_status IN ('Paid', 'Not Paid')),

    order_status VARCHAR(20) NOT NULL DEFAULT 'Completed'
        CHECK (order_status IN ('Completed', 'Cancelled')),

    created_by BIGINT NOT NULL,
    updated_by BIGINT,

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_order_customer
        FOREIGN KEY (customer_id)
        REFERENCES customers(customer_id)
        ON DELETE SET NULL,

    CONSTRAINT fk_order_created_by
        FOREIGN KEY (created_by)
        REFERENCES staff(staff_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_order_updated_by
        FOREIGN KEY (updated_by)
        REFERENCES staff(staff_id)
        ON DELETE SET NULL
);


-- =====================================================
-- 7. ORDER ITEMS TABLE
-- =====================================================

CREATE TABLE order_items (
    order_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_id BIGINT NOT NULL,
    item_id BIGINT NOT NULL,

    -- Product name snapshot
    item_name VARCHAR(150) NOT NULL,

    quantity INTEGER NOT NULL
        CHECK (quantity > 0),

    unit_price NUMERIC(10,2) NOT NULL
        CHECK (unit_price >= 0),

    -- Automatically calculates quantity * unit_price
    total_price NUMERIC(10,2)
        GENERATED ALWAYS AS (quantity * unit_price) STORED,

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_order_item_order
        FOREIGN KEY (order_id)
        REFERENCES orders(order_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_order_item_menu
        FOREIGN KEY (item_id)
        REFERENCES menu_items(item_id)
        ON DELETE RESTRICT
);


-- =====================================================
-- 8. ORDER HISTORY TABLE
-- =====================================================

CREATE TABLE order_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    order_id BIGINT NOT NULL,
    staff_id BIGINT NOT NULL,

    action_type VARCHAR(50) NOT NULL,

    field_name VARCHAR(100),

    old_value TEXT,
    new_value TEXT,

    description TEXT,

    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_history_order
        FOREIGN KEY (order_id)
        REFERENCES orders(order_id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_history_staff
        FOREIGN KEY (staff_id)
        REFERENCES staff(staff_id)
        ON DELETE RESTRICT
);


